#!/usr/bin/env python3
"""
V51.9.169 — writes app/ai-guru-theme.css: AI Guru's Day and Night themes for every page.

Night (default): the AI Guru navy with a soft glow, brighter readable text, clear fonts.
Day: the same pages in light colours. Tailwind v4 colours are CSS variables (`--color-cyan-300` …), so Day swaps each
shade with its mirror (50↔950, 100↔900, 200↔800, 300↔700, 400↔600) and white↔navy, black↔white. Every page turns light
with its own colours kept, without editing the page. The few hand-picked dark hex colours are mapped to light surfaces.

`.ag-keep-dark` keeps a part dark in Day (video, camera); `.ag-light-native` marks a part that is already light (left as it is).
Run:  python3 scripts/make-theme-css.py   (reads node_modules/tailwindcss/theme.css)
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
theme = (ROOT / 'node_modules/tailwindcss/theme.css').read_text()
pal = dict(re.findall(r'--color-([a-z]+-\d+):\s*([^;]+);', theme))
fams = sorted({k.rsplit('-', 1)[0] for k in pal})
MIRROR = {50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 400, 700: 300, 800: 200, 900: 100, 950: 50}

NAVY_INK = '#0F1B33'
PAGE_DARK = '02070d 030912 04101c 050915 050b14 06101c 061321 070a0f 071018 07101a 071321 080c12 04121f'.split()
PANEL_DARK = ('071526 081321 091622 091725 091827 0a1424 0a1828 0a1a2b 0b0f19 0b1017 0b1220 0b1426 0b1626 0b1d2e 0b1e2e '
              '0c0f1b 0c1424 0f1b2e 10141b 101a20 101b32 111d35 161c26 16233f 1a2746 0d2038').split()
TINT = {'2a0b10': '#FDECEC', '2a0b12': '#FDECEC', '2a1a05': '#FFF4DC', '2a1d00': '#FFF4DC', '005c4b': '#E3F6F0'}
DARK_TEXT_ON_BRIGHT = '04101c 04121f 050915 14102a 1a1200 2a1d00 3a1800'.split()

D = 'html[data-theme="day"]'
NOT_KEEP = ':not(.ag-keep-dark):not(.ag-keep-dark *):not(.ag-light-native):not(.ag-light-native *)'

out = []
w = out.append
w('/* Generated by scripts/make-theme-css.py (V51.9.169) — AI Guru Day & Night themes. Edit the script, not this file. */')

# ---------- shared ----------
w(""":root{--ag-font-head:'Sora','Noto Sans','Noto Sans Malayalam',system-ui,sans-serif;--ag-font-body:'Noto Sans','Noto Sans Malayalam','Chilanka','Nirmala UI',system-ui,sans-serif;--ag-accent:#F5B83D;--ag-accent-ink:#F7C661}
html[data-theme="night"],html:not([data-theme]){color-scheme:dark;--ag-bg:#060B18;--ag-text:#EEF2FF;--ag-muted:#A5B0CB;--ag-line:rgba(160,175,210,.18);--ag-panel:#0F1830;--ag-bar:rgba(6,11,24,.78);--ag-tile:rgba(255,255,255,.045);--ag-accent-ink:#F7C661;--ag-accent-soft:rgba(245,184,61,.16);--ag-shadow:0 18px 50px rgba(0,0,0,.45);--ag-glow:radial-gradient(1100px 620px at 82% -10%,rgba(91,120,255,.16),transparent 70%),radial-gradient(800px 520px at -10% 110%,rgba(245,184,61,.07),transparent 70%)}
html[data-theme="day"]{color-scheme:light;--ag-bg:#F4F7FB;--ag-text:#0F1B33;--ag-muted:#475572;--ag-line:rgba(15,27,51,.12);--ag-panel:#FFFFFF;--ag-bar:rgba(244,247,251,.86);--ag-tile:rgba(15,27,51,.035);--ag-accent-ink:#9A5B00;--ag-accent-soft:rgba(245,184,61,.22);--ag-shadow:0 18px 44px rgba(15,27,51,.12);--ag-glow:radial-gradient(1100px 620px at 82% -10%,rgba(120,190,255,.28),transparent 70%),radial-gradient(800px 520px at -10% 110%,rgba(245,184,61,.14),transparent 70%)}
html,body{background:var(--ag-bg)!important;color:var(--ag-text)}
body{background-image:var(--ag-glow)!important;background-attachment:fixed!important;font-family:var(--ag-font-body)!important;-webkit-font-smoothing:antialiased;transition:background-color .35s,color .35s}
h1,h2,h3{font-family:var(--ag-font-head);letter-spacing:-.01em}
h1{letter-spacing:-.02em}
.ai-guru-malayalam,.ai-guru-malayalam *{font-family:"Chilanka","Noto Sans Malayalam","Nirmala UI",sans-serif}
:focus-visible{outline:2px solid var(--ag-accent);outline-offset:2px;border-radius:6px}
::selection{background:rgba(245,184,61,.32)}
*{scrollbar-color:rgba(127,140,170,.45) transparent}
""")

# page roots: transparent, so the glowing background shows
roots = ','.join(f'.min-h-screen[class*="bg-[#{h}]"]' for h in PAGE_DARK)
w(f'{roots}{{background-color:transparent!important}}')

# ---------- readable text (both themes): faint white text is brightened ----------
for a, to in [('30', 62), ('35', 64), ('40', 66), ('45', 68), ('50', 72), ('55', 74)]:
    w(f'.text-white\\/{a}{{color:color-mix(in oklab,var(--color-white) {to}%,transparent)}}')
w('html:not([data-theme="day"]) .text-slate-500,html:not([data-theme="day"]) .text-gray-500{color:var(--color-slate-400)}')
w('html:not([data-theme="day"]) .text-slate-600,html:not([data-theme="day"]) .text-gray-600{color:var(--color-slate-400)}')

# ---------- cards get a little depth (night) ----------
w('html:not([data-theme="day"]) .rounded-2xl.border[class*="bg-[#10141b]"],html:not([data-theme="day"]) .rounded-2xl.border[class*="bg-[#0b1426]"]{background-image:linear-gradient(180deg,rgba(255,255,255,.035),transparent 60%);box-shadow:0 10px 30px rgba(0,0,0,.25)}')

# ---------- Day: mirror the palette ----------
vars_day = []
for f in fams:
    for s, m in MIRROR.items():
        k, km = f'{f}-{s}', f'{f}-{m}'
        if k in pal and km in pal:
            vars_day.append(f'--color-{k}:{pal[km].strip()}')
vars_day += [f'--color-white:{NAVY_INK}', '--color-black:#ffffff']
w(f'{D} body{{{";".join(vars_day)}}}')
vars_orig = [f'--color-{k}:{v.strip()}' for k, v in pal.items() if k.rsplit("-", 1)[0] in fams] + ['--color-white:#fff', '--color-black:#000']
w(f'{D} .ag-keep-dark,{D} .ag-light-native{{{";".join(vars_orig)}}}')
w(f'{D} .ag-keep-dark{{color-scheme:dark}}')

# Day: hand-picked dark surfaces → light
def sel(pref, hexes, extra=''):
    return ','.join(f'{D} [class*="{pref}-[#{h}]"]{NOT_KEEP}{extra}' for h in hexes)
w(f'{sel("bg", PAGE_DARK)}{{background-color:var(--ag-bg)!important}}')
w(f'{sel("bg", PANEL_DARK)}{{background-color:#FFFFFF!important}}')
for h, c in TINT.items():
    w(f'{sel("bg", [h])}{{background-color:{c}!important}}')
w(f'{sel("from", ["0d2038"])}{{--tw-gradient-from:#FFFFFF!important}}')
w(f'{sel("to", ["06101c"])}{{--tw-gradient-to:#F4F7FB!important}}')
w(f'{sel("border", ["04101c"])}{{border-color:rgba(15,27,51,.14)!important}}')
w(f'{sel("text", DARK_TEXT_ON_BRIGHT)}{{color:#FFFFFF!important}}')
# panels that were dark glass get a soft shadow in Day
w(f'{D} .rounded-2xl.border{NOT_KEEP},{D} .rounded-xl.border[class*="bg-[#"]{NOT_KEEP}{{box-shadow:0 1px 2px rgba(15,27,51,.04),0 8px 24px rgba(15,27,51,.05)}}')
# native form controls follow the theme
w(f'{D} select{NOT_KEEP},{D} input{NOT_KEEP},{D} textarea{NOT_KEEP}{{color-scheme:light}}')
w(f'{D} option{{background:#fff;color:{NAVY_INK}}}')

# ---------- Night for the light pages (V51.9.181, UX review item 10) ----------
# Pictures and Credits are drawn light. In Night they now mirror the palette the way Day mirrors the dark pages, so the
# page goes dark like the rest of the app; `.ag-keep-light` (picture cards, the colourful header, dialogs) stays as drawn.
N = 'html:not([data-theme="day"])'
w(f'{N} .ag-light-page{{{";".join(vars_day)};color-scheme:dark}}')
w(f'{N} .ag-light-page .ag-keep-light{{{";".join(vars_orig)};color-scheme:light}}')
w(f'{N} .ag-light-page.min-h-screen{{background-image:none!important;background-color:transparent!important}}')
w(f'{N} .ag-light-page .text-slate-500,{N} .ag-light-page .text-slate-600{{color:var(--color-slate-600)}}')

# ---------- phones: finger-sized controls and readable text (V51.9.181, UX review item 7) ----------
# Under 640 px wide, every button, select, chip-like link and summary is at least 44 px tall (and icon buttons 44 px
# wide), sliders get a taller hit area, and text set below 12 px is shown at 12 px. `.ag-size-as-drawn` opts a part out
# (a scaled-down preview of a reel, say).
OPT = ':not(.ag-size-as-drawn):not(.ag-size-as-drawn *)'
w('@media (max-width:639px){'
  + f'body button{OPT},body select{OPT},body summary{OPT},body [role="button"]{OPT},body a[class*="rounded"]{OPT}{{min-height:44px}}'
  + f'body button{OPT}{{min-width:44px}}'
  + f'body input[type="range"]{OPT}{{min-height:32px}}'
  + f'body input:not([type="range"]):not([type="checkbox"]):not([type="radio"]):not([type="hidden"]){OPT},body textarea{OPT}{{min-height:44px}}'
  + f'body input[type="checkbox"]{OPT},body input[type="radio"]{OPT}{{width:20px;height:20px}}'
  + ','.join(f'body [class~="text-[{n}px]"]{OPT}' for n in (7, 8, 9, 10, 11)) + '{font-size:12px!important;line-height:1.35}'
  + '}')

# ---------- the front page's globe (V51.9.169) ----------
w("""@keyframes agSpin{from{background-position:0 0}to{background-position:-200% 0}}
@keyframes agFloat{0%,100%{transform:translateY(0)}50%{transform:translateY(-8px)}}
@keyframes agOrbit{from{transform:rotate(0)}to{transform:rotate(360deg)}}
.ag-globe-map{background-repeat:repeat-x;background-size:200% 100%;background-image:url(/ai-guru/home/map-night.png);animation:agSpin 48s linear infinite}
html[data-theme="day"] .ag-globe-map{background-image:url(/ai-guru/home/map-day.png)}
.ag-globe{box-shadow:0 0 0 1px rgba(150,190,255,.25),0 0 80px rgba(80,140,255,.25)}
html[data-theme="day"] .ag-globe{box-shadow:0 0 0 1px rgba(15,60,130,.18),0 30px 80px rgba(60,120,200,.2)}
.ag-globe-shade{background:radial-gradient(circle at 34% 30%,rgba(255,255,255,.10),transparent 42%),radial-gradient(circle at 50% 50%,transparent 58%,rgba(6,11,24,.75) 100%)}
html[data-theme="day"] .ag-globe-shade{background:radial-gradient(circle at 34% 30%,rgba(255,255,255,.55),transparent 40%),radial-gradient(circle at 50% 50%,transparent 60%,rgba(120,170,230,.35) 100%)}
.ag-globe-halo{background:radial-gradient(circle,rgba(103,178,255,.2) 0%,rgba(103,178,255,.05) 45%,transparent 70%)}
html[data-theme="day"] .ag-globe-halo{background:radial-gradient(circle,rgba(120,190,255,.3) 0%,rgba(120,190,255,.08) 45%,transparent 70%)}
.ag-orbit,.ag-ring{border-color:rgba(160,190,255,.22)}
html[data-theme="day"] .ag-orbit,html[data-theme="day"] .ag-ring{border-color:rgba(15,60,130,.2)}
.ag-ring{transform:rotate(-18deg)}
.ag-orbit{animation:agOrbit 90s linear infinite}
.ag-chip{animation:agFloat 6s ease-in-out infinite}
.ag-cta{box-shadow:0 10px 30px rgba(245,184,61,.28)}
@media (prefers-reduced-motion:reduce){.ag-globe-map,.ag-orbit,.ag-chip{animation:none}}""")

# ---------- the floating Play button (V51.9.171) ----------
w("""@keyframes agPulse{0%{box-shadow:0 0 0 0 rgba(245,165,36,.55)}70%{box-shadow:0 0 0 18px rgba(245,165,36,0)}100%{box-shadow:0 0 0 0 rgba(245,165,36,0)}}
.ag-playfab-pulse{animation:agPulse 2.2s ease-out infinite}
.ag-playfab-on{box-shadow:0 0 0 2px rgba(245,184,61,.35),0 18px 44px rgba(0,0,0,.35)!important}
@media (prefers-reduced-motion:reduce){.ag-playfab-pulse{animation:none}}""")

(ROOT / 'app/ai-guru-theme.css').write_text('\n'.join(out) + '\n')
print('wrote app/ai-guru-theme.css', sum(len(x) for x in out), 'bytes,', len(vars_day), 'day colours')
